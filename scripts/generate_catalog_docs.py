def link(source: Path, destination: Path, label: str) -> str:
    """Return a portable Markdown link relative to the containing document."""
    relative = Path(os.path.relpath(destination, source.parent)).as_posix()
    return f'[{label}]({relative})'


def is_complete(algorithm: dict) -> bool:
    ready = {'implemented', 'tested', 'reviewed'}
    return (
        all(algorithm[field] in ready for field in STATUS_FIELDS[:3])
        and algorithm['test_status'] in {'tested', 'reviewed'}
    )


def overall_status(algorithm: dict) -> str:
    if is_complete(algorithm):
        return 'complete'
    statuses = [algorithm[field] for field in STATUS_FIELDS]
    if 'blocked' in statuses:
        return 'blocked'
    if all(status == 'planned' for status in statuses):
        return 'planned'
    return 'in-progress'


def navigation(path: Path) -> str:
    return ' · '.join([
        link(path, ROOT / 'README.md', 'Project home'),
        link(path, ROOT / 'docs/algorithm-index.md', 'Complete index'),
        link(path, ROOT / 'docs/progress.md', 'Progress'),
    ])


def index_page(catalog: dict, algorithms: dict) -> str:
    path = ROOT / 'docs/algorithm-index.md'
    total = sum(len(category['items']) for category in catalog['categories'])
    lines = [
        '# Complete Algorithm Index', '', GENERATED_MARKER, '',
        f'The original syllabus contains **{total} entries** in '
        f'**{len(catalog["categories"])} categories**, mapped to '
        f'**{len(algorithms)} unique canonical topics**. Every original label is '
        'retained below in its original category and order. Repeated topics link '
        'to one canonical folder; meaningful variants have their own records.', '',
        'Status describes catalog progress. A planning README is an outline of '
        'future scope and does not mean the full algorithm article, Python or '
        'C++ implementation, or algorithm tests exist.', '',
        'Foundation checks validate repository structure; they are separate from '
        'tests of completed algorithms.', '', navigation(path), '',
    ]
    for category in catalog['categories']:
        category_link = link(path, ROOT / category['path'] / 'README.md', category['name'])
        lines += [f'## {category["id"]}. {category_link}', '',
                  '| Original syllabus entry | Canonical topic | Status |',
                  '| --- | --- | --- |']
        for item in category['items']:
            algorithm = algorithms[item['algorithm']]
            target = ROOT / algorithm['canonical_location'] / 'README.md'
            lines.append(
                f'| {item["name"]} | {link(path, target, algorithm["id"])} '
                f'| {overall_status(algorithm)} |'
            )
        lines.append('')
    lines += [
        '## Canonicalization decisions', '',
        '- BFS, DFS, A* Search, the repeated graph algorithms, CNNs, Minimax, '
        'genetic algorithms, simulated annealing, PSO, and ACO share canonical '
        'topics across their original memberships.',
        '- Exhaustive Search and Brute Force Search retain both syllabus labels '
        'and share one finite-candidate enumeration topic.',
        '- Vanilla Autoencoders and Autoencoders for Dimensionality Reduction '
        'share a reconstruction autoencoder with a bottleneck representation. '
        'Denoising, sparse, and variational autoencoders remain distinct variants.',
        '- LDA classification and supervised LDA projection have separate '
        'canonical folders because their prediction and transformation contracts '
        'are meaningful variants. Their shared mathematics is linked explicitly.',
        '- HMM part-of-speech tagging, tree level-order traversal, recursive '
        'versus bitmask subset generation, backtracking versus dynamic-programming '
        'subset sum, and the two maximum-subarray formulations remain meaningful '
        'variants with separate contracts.',
        '- Dynamic Policy Optimization remains blocked until the maintainer '
        'identifies the intended source. Direct Preference Optimization is not '
        'substituted. See '
        + link(path, ROOT / 'docs/terminology-decisions.md', 'terminology decisions') + '.', '',
        'The machine-readable source is '
        + link(path, ROOT / 'catalog.yaml', 'catalog.yaml')
        + '; full documentation and implementation standards are in '
        + link(path, ROOT / 'CONTRIBUTING.md', 'CONTRIBUTING.md') + '.', '',
    ]
    return '\n'.join(lines)


def progress_page(catalog: dict, algorithms: dict) -> str:
    """Render catalog evidence and the explicitly authorized development scope."""
    path = ROOT / 'docs/progress.md'
    state = catalog.get('development', {})
    total = sum(len(category['items']) for category in catalog['categories'])
    completed = [a for a in algorithms.values() if is_complete(a)]
    blocked = [a for a in algorithms.values() if overall_status(a) == 'blocked']
    statuses = Counter(overall_status(a) for a in algorithms.values())
    phase = state.get('phase', 'Phase 0 — Foundation')
    scope = state.get('scope', 'Foundation only; awaiting explicit approval')
    status = state.get('status', 'awaiting-review')
    lines = [
        '# Project Progress', '', GENERATED_MARKER, '',
        f'**Current development phase: {phase}.**', '',
        f'**Authorized scope:** {scope}. **Checkpoint status:** {status}.', '',
        '| Measure | Count |', '| --- | ---: |',
        f'| Original syllabus/catalog entries | {total} |',
        f'| Syllabus categories | {len(catalog["categories"])} |',
        f'| Unique canonical algorithms/topics | {len(algorithms)} |',
        f'| Reused syllabus memberships | {total - len(algorithms)} |',
        f'| Completed algorithms | {len(completed)} |',
        f'| Remaining algorithms, including blocked topics | {len(algorithms) - len(completed)} |',
        f'| Planned canonical topics | {statuses["planned"]} |',
        f'| In-progress canonical topics | {statuses["in-progress"]} |',
        f'| Blocked canonical topics | {statuses["blocked"]} |', '',
        'Completion requires full educational documentation, both language '
        'implementations, runnable examples, and genuinely passed algorithm '
        'tests. A planning README alone does not satisfy those requirements. '
        'Completed does not imply human review or approval for another category.', '',
        '## Completed algorithms', '',
    ]
    lines += [
        '- ' + link(path, ROOT / a['canonical_location'] / 'README.md', a['name'])
        for a in completed
    ] or ['None recorded yet.']
    lines += ['', '## Current authorized work and resume checkpoint', '']
    if state:
        searching = state.get('scope') == 'Searching category only'
        label = 'searching' if searching else 'sorting'
        batches = state.get('completed_batches', [])
        lines.append(f'Validated {label} batches: ' +
                     (', '.join(str(batch) for batch in batches) if batches else 'none yet') + '.')
        active = state.get('active_batch')
        lines += ['', f'Active batch: {active if active is not None else "none; awaiting user review"}.']
        if state.get('checkpoint'):
            lines += ['', 'Actual commands, results, and resume instructions are saved in '
                      + link(path, ROOT / state['checkpoint'], f'{label} checkpoints') + '.']
        if state.get('completion_report'):
            lines += ['', 'See the '
                      + link(path, ROOT / state['completion_report'], f'{label} completion report') + '.']
        if searching:
            lines += ['', 'The owner approved Phase 1 (Sorting). Phase 2 authorizes '
                      'Searching only: Batch 1: Linear, Binary, Jump; Batch 2: '
                      'Interpolation, Exponential, Ternary. Finish and validate each '
                      'batch before automatically continuing. No approval is needed '
                      'between these internal batches.', '',
                      'After all six searches are complete, stop for the user’s '
                      'review. Every other category requires explicit approval.']
        else:
            lines += ['', 'The approved order is Batch 1: Bubble, Selection, Insertion, '
                  'Merge; Batch 2: Quick, Heap, Counting, Radix; Batch 3: Bucket, '
                  'Shell, Tim. Finish and validate each batch before automatically '
                  'continuing. No approval is required between these internal batches.', '',
                  'After all 11 sorting algorithms are complete, stop for the user’s '
                  'review. Searching and every other category require explicit approval.']
    else:
        lines += ['Foundation prepared; algorithm implementation requires explicit approval.']
    lines += ['', '## Foundation and CI', '',
              'Phase 0 is preserved in '
              + link(path, ROOT / 'docs/phase-0-review.md', 'the foundation review') + '.', '',
              'The workflow runs lightweight validation and Python/C++ tests. '
              'Local results are not hosted GitHub Actions results; no remote '
              'CI pass is claimed without a workflow run.', '',
              '## Known blockers and scope decisions', '']
    for algorithm in blocked:
        lines.append('- ' + link(path, ROOT / algorithm['canonical_location'] / 'README.md', algorithm['name'])
                     + ': ' + algorithm['notes'])
    lines += ['', 'The intended Dynamic Policy Optimization reference remains '
              'unresolved; see '
              + link(path, ROOT / 'docs/terminology-decisions.md', 'terminology decisions') + '.', '',
              'Advanced models require explicit educational scope, dependencies, '
              'datasets, and compute limits in their approved phases.', '',
              '## Approval boundary', '',
              f'The current authorization is {scope}. '
              'Do not begin another category without explicit user approval. '
              'Do not commit, push, or publish without permission.', '',
              navigation(path), '']
    return '\n'.join(lines)


def category_page(category: dict, algorithms: dict) -> str:
    path = ROOT / category['path'] / 'README.md'
    lines = [
        f'# {category["name"]}', '', GENERATED_MARKER, '',
        CATEGORY_PURPOSES[category['id']], '',
        f'This category preserves **{len(category["items"])} original syllabus '
        'entries**. Each link points to the canonical topic; repeated '
        'memberships do not create copied implementations. Topic planning pages '
        'record future scope; completed topics have their full lessons and tests.', '',
        '| Original syllabus entry | Canonical folder | Status |',
        '| --- | --- | --- |',
    ]
    for item in category['items']:
        algorithm = algorithms[item['algorithm']]
        target = ROOT / algorithm['canonical_location'] / 'README.md'
        lines.append(f'| {item["name"]} | {link(path, target, algorithm["id"])} '
                     f'| {overall_status(algorithm)} |')
    lines += [
        '', '## Learning and contribution scope', '',
        'Choose prerequisites through the '
        + link(path, ROOT / 'docs/learning-roadmap.md', 'learning roadmap')
        + '. Each future completed topic must include the full 25-part '
        'educational article, working Python and C++ programs, executable '
        'examples, accurate complexity analysis, and relevant tests described '
        'in ' + link(path, ROOT / 'CONTRIBUTING.md', 'the contribution standards') + '.', '',
        'Completion is shown by the catalog status and topic artifacts. The '
        'current implementation authorization is recorded in the progress tracker; '
        'other categories require explicit user approval.', '', navigation(path), '',
    ]
    return '\n'.join(lines)


def algorithm_page(algorithm: dict, memberships: list[tuple[dict, dict]], algorithms: dict) -> str:
    path = ROOT / algorithm['canonical_location'] / 'README.md'
    lines = [
        f'# {algorithm["name"]}', '', PLANNING_MARKER, '',
        '**Planned topic.** The full educational algorithm article, '
        'Python implementation, C++ implementation, executable examples, and '
        'algorithm tests have not been created.', '',
        '## Purpose and planned scope', '', algorithm['notes'], '',
        f'**Planned learning difficulty:** {algorithm["difficulty"]}.', '',
        f'**Canonical location:** `{algorithm["canonical_location"]}`.', '',
        '## Original syllabus memberships', '',
    ]
    for category, item in memberships:
        lines.append('- ' + link(path, ROOT / category['path'] / 'README.md',
                                 f'{category["id"]}. {category["name"]}')
                     + f' — {item["name"]}.')
    lines += [
        '', '## Current status', '',
        '| Deliverable | Status |', '| --- | --- |',
        f'| Full algorithm documentation | {algorithm["documentation_status"]} |',
        f'| Python implementation | {algorithm["python_status"]} |',
        f'| C++ implementation | {algorithm["cpp_status"]} |',
        f'| Algorithm tests | {algorithm["test_status"]} |', '',
        'A planning README does not satisfy the completed documentation '
        'requirement. No implementation files or algorithm tests are currently '
        'available for this planned topic.', '',
        '## Requirements before completion', '',
        'In an approved implementation phase, define the input/output contract '
        'and prerequisites; write the full 25-part article with intuition, '
        'working process, pseudocode, dry run, bounded complexity analysis, '
        'applications, limitations, and verifiable references; add Python and '
        'C++ implementations with reproducible usage; and execute meaningful '
        'edge-case tests. Follow '
        + link(path, ROOT / 'CONTRIBUTING.md', 'the project contribution standards')
        + ' and update the catalog only when evidence supports each status.', '',
        '## Related planned topics', '',
    ]
    for identifier in algorithm['related_algorithms']:
        related = algorithms[identifier]
        lines.append('- ' + link(path, ROOT / related['canonical_location'] / 'README.md', related['name']))
    if algorithm['id'] == 'dynamic-policy-optimization':
        lines += ['', '## Decision required', '',
                  'The maintainer must identify the intended paper or precise '
                  'definition before algorithm work can start. See '
                  + link(path, ROOT / 'docs/terminology-decisions.md', 'verified terminology and candidate references') + '.']
    lines += [
        '', '## Review gate and attribution', '',
        'Check the progress tracker for the current authorization. Do not begin this '
        'planned topic until it is included in the user’s approved scope.', '',
        'Algorithm Atlas is maintained by '
        '[MD.Khalid Hasan](https://github.com/khalidhasan7343). Contribution and '
        'review rules are in '
        + link(path, ROOT / 'CONTRIBUTING.md', 'CONTRIBUTING.md') + '.', '',
        navigation(path), '',
    ]
    return '\n'.join(lines)


def parent_pages(catalog: dict) -> dict[Path, str]:
    groups = {
        'dsa': ('Data Structures and Algorithms', 'Foundational, core, and advanced techniques for discrete computational problems.', lambda c: c['id'].startswith('A')),
        'machine-learning': ('Machine Learning', 'Supervised, unsupervised, neural, sequential, and optimization topics with planned reproducible educational scope.', lambda c: c['id'].startswith('B')),
        'machine-learning/supervised-learning': ('Supervised Learning', 'Models that learn from labeled observations for regression and classification.', lambda c: c['id'] in {'B1', 'B2'}),
        'machine-learning/unsupervised-learning': ('Unsupervised Learning and Representation Categories', 'Clustering, association patterns, and representations. This required directory also includes explicitly supervised LDA projection; its label and supervision requirement are retained.', lambda c: c['id'] in {'B4', 'B5', 'B6'}),
        'artificial-intelligence': ('Artificial Intelligence', 'Search, constrained reasoning, strategic interaction, fuzzy inference, swarm methods, and vision.', lambda c: c['id'].startswith('C')),
    }
    pages = {}
    for directory, (name, description, predicate) in groups.items():
        path = ROOT / directory / 'README.md'
        lines = [f'# {name}', '', GENERATED_MARKER, '', description, '',
                 'The links below preserve the complete syllabus and lead to '
                 'canonical topics. Consult their statuses for full lessons and tested '
                 'implementations; planned topics remain scope records only.', '']
        for category in filter(predicate, catalog['categories']):
            lines.append('- ' + link(path, ROOT / category['path'] / 'README.md',
                                     f'{category["id"]}. {category["name"]}'))
        lines += ['', 'Select prerequisites through '
                  + link(path, ROOT / 'docs/learning-roadmap.md', 'the learning roadmap')
                  + ' and inspect the mandatory approval checkpoint in '
                  + link(path, ROOT / 'docs/progress.md', 'the progress tracker') + '.',
                  '', navigation(path), '']
        pages[path] = '\n'.join(lines)
    return pages


def expected_pages(catalog: dict) -> dict[Path, str]:
    algorithms = {algorithm['id']: algorithm for algorithm in catalog['algorithms']}
    memberships = {identifier: [] for identifier in algorithms}
    for category in catalog['categories']:
        for item in category['items']:
            memberships[item['algorithm']].append((category, item))
    pages = parent_pages(catalog)
    pages[ROOT / 'docs/algorithm-index.md'] = index_page(catalog, algorithms)
    pages[ROOT / 'docs/progress.md'] = progress_page(catalog, algorithms)
    for category in catalog['categories']:
        pages[ROOT / category['path'] / 'README.md'] = category_page(category, algorithms)
    for algorithm in algorithms.values():
        path = ROOT / algorithm['canonical_location'] / 'README.md'
        planning = all(algorithm[field] in {'planned', 'blocked'} for field in STATUS_FIELDS)
        if not planning:
            continue
        if path.exists() and PLANNING_MARKER not in path.read_text(encoding='utf-8'):
            continue
        pages[path] = algorithm_page(algorithm, memberships[algorithm['id']], algorithms)
    return pages


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Report generated-document drift without writing.')
    args = parser.parse_args()
    with (ROOT / 'catalog.yaml').open(encoding='utf-8') as stream:
        catalog = yaml.safe_load(stream)
    pages = expected_pages(catalog)
    changed = []
    for path, content in pages.items():
        if path.exists() and path.read_text(encoding='utf-8') == content:
            continue
        changed.append(path.relative_to(ROOT).as_posix())
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8')
    if args.check and changed:
        print('Generated documentation needs updating:')
        print('\n'.join(changed))
        return 1
    action = 'Checked' if args.check else 'Generated/updated'
    print(f'{action} {len(pages)} catalog documentation pages; {len(changed)} changes.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
