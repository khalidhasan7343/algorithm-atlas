"""Maintain catalog navigation, progress, and honest topic planning pages.

Run from any directory. ``--check`` reports drift without changing files.
Algorithm planning pages are managed only while they carry our planning marker
and all topic statuses remain planned/blocked. Authored or developed algorithm
documentation is preserved, including during future catalog regeneration.
Progress reads the development state from catalog.yaml; phase instructions
and the batch checkpoint must agree with that authorized scope.
"""

