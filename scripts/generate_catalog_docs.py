        f'| Syllabus categories | {len(catalog["categories"])} |',
        f'| Unique canonical algorithms/topics | {len(algorithms)} |',
        f'| Reused syllabus memberships | {total - len(algorithms)} |',
        f'| Completed algorithms | {len(completed)} |',
        f'| Remaining algorithms, including blocked topics | {len(algorithms) - len(completed)} |',
        f'| Planned canonical topics | {statuses["planned"]} |',
        f'| Blocked canonical topics | {statuses["blocked"]} |', '',
